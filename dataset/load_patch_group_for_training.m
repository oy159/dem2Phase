function sample = load_patch_group_for_training(filename, varargin)
%LOAD_PATCH_GROUP_FOR_TRAINING Strict masked loader for grouped MAT samples.
    p = inputParser;
    addRequired(p, 'filename', @(x) ischar(x) || isstring(x));
    addParameter(p, 'phase_field', 'wrappedphase_withnoise', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'strict', true, @(x) islogical(x) || isnumeric(x));
    parse(p, filename, varargin{:});
    opt = p.Results;
    data = load(filename);
    phase_field = char(opt.phase_field);
    required = {phase_field, 'coherence_observed', 'valid_edge_mask', ...
        'coregistration_valid_mask', 'edge_index', 'baseline_perp_m', ...
        'ambiguity_height_m', 'failure_labels', 'metadata'};
    for idx = 1:numel(required)
        assert(isfield(data, required{idx}), 'dem2phase:MissingTrainingField', ...
            'Training sample %s lacks field %s.', filename, required{idx});
    end

    phase = data.(phase_field);
    coherence = data.coherence_observed;
    assert(ndims(phase) == 3 && isequal(size(phase), size(coherence)), ...
        'dem2phase:InvalidTrainingStack', ...
        'Phase and observed coherence must share [K,H,W].');
    num_edges = size(phase,1);
    edge_mask = logical(data.valid_edge_mask(:));
    assert(numel(edge_mask) == num_edges && any(edge_mask), ...
        'dem2phase:InvalidTrainingEdgeMask', ...
        'valid_edge_mask must retain at least one of K edges.');
    pixel_mask = logical(data.coregistration_valid_mask);
    assert(isequal(size(pixel_mask), size(phase)), ...
        'dem2phase:InvalidTrainingPixelMask', ...
        'coregistration_valid_mask must have shape [K,H,W].');
    active_cube = repmat(reshape(edge_mask, [], 1, 1), ...
        1, size(phase,2), size(phase,3));
    pixel_mask = pixel_mask & active_cube;

    if logical(opt.strict)
        inactive = ~active_cube;
        assert(all(abs(double(phase(inactive))) <= 1e-7) && ...
            all(abs(double(coherence(inactive))) <= 1e-7), ...
            'dem2phase:InactiveEdgeNotZeroFilled', ...
            'Inactive phase/coherence edges must be zero-filled.');
        assert(all(isfinite(double(phase(pixel_mask)))) && ...
            all(isfinite(double(coherence(pixel_mask)))), ...
            'dem2phase:NonfiniteTrainingObservation', ...
            'Active valid observations must be finite.');
        method = char(data.metadata.coherence_observation_method);
        assert(strcmp(method, 'observed_node_slc_pair'), ...
            'dem2phase:LeakyCoherenceInput', ...
            ['Strict training rejects coherence derived using clean phase. ' ...
             'Regenerate the sample with observed node-SLC coherence.']);
        split_fields = {'dataset_split', 'split_group', 'geographic_tile', ...
            'geographic_region', 'source_dataset', 'source_quality_role'};
        assert(all(isfield(data.metadata, split_fields)), ...
            'dem2phase:MissingDatasetSplit', ...
            'Strict training requires whole-DEM split metadata.');
        assert(ismember(char(data.metadata.dataset_split), ...
            {'train', 'test', 'validation'}), ...
            'dem2phase:InvalidDatasetSplit', ...
            'metadata.dataset_split must be train, test, or validation.');
    end

    sample.phase = phase;
    sample.coherence_observed = coherence;
    sample.valid_edge_mask = edge_mask;
    sample.valid_pixel_mask = pixel_mask;
    sample.edge_index = data.edge_index;
    sample.baseline_perp_m = data.baseline_perp_m;
    sample.ambiguity_height_m = data.ambiguity_height_m;
    sample.failure_labels = data.failure_labels;
    sample.metadata = data.metadata;
    if isfield(data.metadata, 'dataset_split')
        sample.dataset_split = char(data.metadata.dataset_split);
    end
    if isfield(data, 'unwrapped_phase')
        sample.target_unwrapped_phase = data.unwrapped_phase;
    end
    if isfield(data, 'coherence_true')
        sample.target_coherence_true = data.coherence_true;
    end
end
