function assignments = load_dem_split_manifest(filename, available_dem_files)
%LOAD_DEM_SPLIT_MANIFEST Validate whole-DEM train/test/validation assignment.
    assignments = readtable(filename, 'TextType', 'string');
    required = {'dem_file', 'geographic_tile', 'split', 'region', ...
        'quality_role', 'patches_per_dem', 'latitude_deg', ...
        'longitude_deg', 'source'};
    missing = setdiff(required, assignments.Properties.VariableNames);
    assert(isempty(missing), 'dem2phase:InvalidSplitManifest', ...
        'Split manifest is missing columns: %s', strjoin(missing, ', '));

    names = lower(strtrim(assignments.dem_file));
    assert(all(strlength(names) > 0) && numel(unique(names)) == height(assignments), ...
        'dem2phase:DuplicateDemSplit', ...
        'Each DEM filename must occur exactly once in the split manifest.');
    assignments.split = lower(strtrim(assignments.split));
    assert(all(ismember(assignments.split, ["train", "test", "validation"])), ...
        'dem2phase:InvalidDatasetSplit', ...
        'Split values must be train, test, or validation.');
    geographic_tiles = upper(strtrim(assignments.geographic_tile));
    assert(all(~cellfun('isempty', regexp(cellstr(geographic_tiles), ...
        '^[NS]\d{2,3}[EW]\d{3}$', 'once'))), ...
        'dem2phase:InvalidGeographicTile', ...
        'geographic_tile must use a token such as N27E085.');
    [tile_group, tile_name] = findgroups(geographic_tiles);
    tile_split_count = splitapply(@(value) numel(unique(value)), ...
        assignments.split, tile_group);
    leaking_tiles = tile_name(tile_split_count > 1);
    assert(isempty(leaking_tiles), 'dem2phase:GeographicSplitLeakage', ...
        'Geographic tiles assigned to multiple splits: %s', ...
        strjoin(leaking_tiles, ', '));
    assignments.geographic_tile = geographic_tiles;
    counts = double(assignments.patches_per_dem);
    assert(all(isfinite(counts) & counts >= 1 & counts == fix(counts)), ...
        'dem2phase:InvalidSplitPatchCount', ...
        'patches_per_dem must contain positive integers.');
    assert(all(isfinite(assignments.latitude_deg) & ...
        assignments.latitude_deg >= -90 & assignments.latitude_deg <= 90) && ...
        all(isfinite(assignments.longitude_deg) & ...
        assignments.longitude_deg >= -180 & assignments.longitude_deg <= 180), ...
        'dem2phase:InvalidSplitCoordinate', ...
        'Manifest latitude/longitude values are invalid.');

    if nargin >= 2 && ~isempty(available_dem_files)
        available = lower(string(available_dem_files(:)));
        unknown = setdiff(available, names);
        absent = setdiff(names, available);
        assert(isempty(unknown), 'dem2phase:UnassignedDem', ...
            'DEM files without a split assignment: %s', strjoin(unknown, ', '));
        assert(isempty(absent), 'dem2phase:MissingAssignedDem', ...
            'Split manifest references missing DEM files: %s', strjoin(absent, ', '));
    end
end
